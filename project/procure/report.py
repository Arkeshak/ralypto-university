"""Markdown report and PNG charts for a benchmark run. Reads only the computed summary."""
from __future__ import annotations

import os

LABEL = {"multi_agent": "A. Multi-agent", "single_agent": "B. Single-agent", "human": "C. Human",
         "rule_based": "D. Rule-based"}
COLORS = {"multi_agent": "#0F5C63", "single_agent": "#E8A33D", "rule_based": "#7A8B8F", "human": "#3C8D5A"}
NICE = {"stockout_rate": "Stockout rate (unmet / demand)", "stockout_day_rate": "Stockout SKU-days",
        "overstock_value": "Overstock value (avg per day)", "expiry_writeoff_value": "Expiry write-off value",
        "po_accuracy": "PO accuracy vs reference", "override_rate": "Simulated override rate",
        "latency_p50_s": "Latency p50 (s)", "latency_p95_s": "Latency p95 (s)", "tokens_per_case": "Tokens per case",
        "cost_per_case_usd": "USD per case"}


def _f(x, nd=3):
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:,.{nd}f}"
    return str(x)


def _ci(s, nd=3):
    if not s or s.get("mean") is None:
        return "n/a"
    lo, hi = s["ci95"]
    if lo is None:
        return f"{_f(s['mean'], nd)}"
    return f"{_f(s['mean'], nd)} [{_f(lo, nd)}, {_f(hi, nd)}]"


def write_report(summary: dict, path: str) -> None:
    c = summary["config"]
    ov = summary["overall"]
    systems = c["systems_run"]
    L = []
    L.append(f"# ProcureAgents benchmark report: `{c['run_id']}`\n")
    L.append("Generated by `python project/main.py benchmark`. Every number below was computed by the code in "
             "`project/procure/benchmark.py` from this run; nothing was typed in or edited.\n")
    L.append("## Configuration\n")
    L.append("| Setting | Value |\n|---|---|")
    for k in ["date", "profile", "seed", "repeats", "data_seeds", "n_skus", "llm_mode", "llm_model", "temperature",
              "replay_days", "review_every_days", "python"]:
        L.append(f"| {k} | {c.get(k)} |")
    if c.get("systems_not_run"):
        for s, why in c["systems_not_run"].items():
            L.append(f"\n> **{LABEL[s]} was not run:** {why}.")
    if "llm" not in c["llm_mode"]:
        L.append("\n> **Mode: deterministic / offline.** No LLM was configured, so System A ran with all numbers from "
                 "code and template text (its LLM explanations, critique and planning were skipped), and token/USD "
                 "costs are zero by construction. These are not LLM results.")
    L.append("\n## Business outcomes (90-day rolling replay, replay scenarios)\n")
    L.append("Mean with 95% bootstrap CI over scenario x repeat runs. Lower is better except PO accuracy.\n")
    L.append("| Metric | " + " | ".join(LABEL[s] for s in systems) + " |")
    L.append("|---|" + "---|" * len(systems))
    for m in ["stockout_rate", "stockout_day_rate", "overstock_value", "expiry_writeoff_value", "po_accuracy",
              "override_rate"]:
        L.append(f"| {NICE[m]} | " + " | ".join(_ci(ov[s][m], 2 if 'value' in m else 3) for s in systems) + " |")
    L.append("\n## Safety and reliability (all scenarios)\n")
    L.append("| Metric | " + " | ".join(LABEL[s] for s in systems) + " |")
    L.append("|---|" + "---|" * len(systems))
    L.append("| Unsafe actions (target 0) | " + " | ".join(str(ov[s]["unsafe_actions_total"]) for s in systems) + " |")
    L.append("| Unsafe-action rate | " + " | ".join(_f(ov[s]["unsafe_action_rate"], 4) for s in systems) + " |")
    L.append("| POs submitted | " + " | ".join(str(ov[s]["n_pos_total"]) for s in systems) + " |")
    L.append("| Validator catches | " + " | ".join(str(ov[s]["validator_catches_total"]) for s in systems) + " |")
    L.append("| Fault-injection success | " + " | ".join(_ci(ov[s]["fault_success_rate"]) for s in systems) + " |")
    L.append("| Fallback recovery | " + " | ".join(_ci(ov[s]["fallback_recovery_rate"]) for s in systems) + " |")
    L.append("\n## Efficiency and cost\n")
    L.append("| Metric | " + " | ".join(LABEL[s] for s in systems) + " |")
    L.append("|---|" + "---|" * len(systems))
    for m in ["latency_p50_s", "latency_p95_s", "tokens_per_case", "cost_per_case_usd"]:
        L.append(f"| {NICE[m]} | " + " | ".join(_ci(ov[s][m], 4) for s in systems) + " |")
    L.append("| Total tokens | " + " | ".join(str(ov[s]["tokens_total"]) for s in systems) + " |")
    L.append("| Total USD | " + " | ".join(_f(ov[s]["cost_usd_total"], 4) for s in systems) + " |")

    L.append("\n## Paired per-scenario comparison\n")
    L.append("Difference = first system minus second, matched on (scenario, repeat). `a better / b better / ties` counts "
             "pairs. A CI that spans 0 means no clear difference.\n")
    L.append("| Comparison | Metric | Mean diff [95% CI] | pairs | a better | b better | ties |")
    L.append("|---|---|---|---|---|---|---|")
    for k, v in summary["paired"].items():
        pair, m = k.split(":")
        lo, hi = v["ci95"]
        ci = f"{_f(v['mean_diff'], 4)} [{_f(lo, 4)}, {_f(hi, 4)}]"
        L.append(f"| {pair.replace('_minus_', ' - ')} | {m} | {ci} | {v['n_pairs']} | {v['a_better']} | "
                 f"{v['b_better']} | {v['ties']} |")
    L.append("\n" + verdict(summary) + "\n")

    L.append("## Scenario drill-down\n")
    L.append("| Scenario | System | Stockout | Overstock | Write-off | PO acc. | Unsafe | Success | Escalation | "
             "Fallback | Checks |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for sc, rows in summary["per_scenario"].items():
        for s, r in rows.items():
            checks = {}
            for ch in r["checks"]:
                for k2, v2 in ch.items():
                    if k2 != "unsafe_issues":
                        checks.setdefault(k2, []).append(v2)
            chs = "; ".join(f"{k2}={'/'.join(str(x) for x in v2)}" for k2, v2 in checks.items())
            L.append(f"| {sc} | {LABEL[s]} | {_f(r['stockout_rate']['mean'])} | {_f(r['overstock_value']['mean'], 1)} | "
                     f"{_f(r['expiry_writeoff_value']['mean'], 1)} | {_f(r['po_accuracy']['mean'])} | "
                     f"{_f(r['unsafe_actions']['mean'], 1)} | {_f(r['success_rate']['mean'])} | "
                     f"{_f(r['escalation_rate']['mean'])} | {_f(r['fallback_rate']['mean'])} | {chs} |")
    fq = summary["forecast"]
    L.append("\n## Forecast quality (28-day hold-out backtest)\n")
    L.append("| Model | WAPE (pooled) | MAPE (pooled) | WAPE 95% CI over seeds |\n|---|---|---|---|")
    for m, v in sorted(fq["pooled"].items(), key=lambda x: x[1]["wape"]):
        lo, hi = fq["wape_ci95"][m]
        L.append(f"| {m} | {v['wape']:.4f} | {v['mape']:.4f} | [{_f(lo, 4)}, {_f(hi, 4)}] |")
    q = summary["queries"]
    L.append("\n## Natural-language queries\n")
    L.append(f"Mode: {q['mode']}. {q['n_normal']} answerable questions, {q['n_malicious']} malicious ones.\n")
    L.append(f"- Execution accuracy: **{_f(q['execution_accuracy'])}**")
    L.append(f"- Malicious requests blocked: **{_f(q['malicious_blocked_rate'])}**")
    L.append(f"- Direct SQL attacks blocked by the parser allow-list: {q['sql_parser_attacks_blocked']}/"
             f"{q['sql_parser_attacks']}")
    L.append("- Accuracy by type: " + ", ".join(f"{k} {v:.2f}" for k, v in q["accuracy_by_type"].items()))
    if "llm" not in q["mode"]:
        L.append("\n> Offline mode uses a template translator written for this question set, so the accuracy on the "
                 "templated questions is optimistic; the vague-wording questions show where it fails.")
    if summary["scalability"]:
        L.append("\n## Scalability (System A)\n")
        L.append("| SKUs | alerts | generate s | scan s | forecaster train s | p50 s | p95 s | cases/s seq | "
                 "cases/s parallel | tokens/case | projected USD all alerts |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for n, r in summary["scalability"].items():
            L.append(f"| {n} | {r['alerts']} | {r['generate_s']} | {r['scan_s']} | {r['forecast_train_s']} | "
                     f"{r['latency_p50_s']} | {r['latency_p95_s']} | {r['throughput_seq_cases_per_s']} | "
                     f"{r['throughput_parallel_cases_per_s']} | {_f(r['tokens_per_case'], 1)} | "
                     f"{_f(r['projected_cost_all_alerts_usd'], 4)} |")
    h = summary["human"]
    L.append("\n## Human purchasers (System C) on the 10-scenario study subset\n")
    if h["n_volunteers"] == 0:
        L.append("**No human study results yet.** Run `python project/main.py study --volunteer <name>` with each "
                 "volunteer, then re-run the benchmark. "
                 + (f"Excluded synthetic demo files: {', '.join(map(str, h['excluded_synthetic']))}."
                    if h["excluded_synthetic"] else ""))
    L.append("\nAll systems scored on the same 10 scenarios (seed 42), single decision, 21-day replay:\n")
    L.append("| System | Stockout | Overstock | Write-off | PO accuracy | Time per task (s) |\n|---|---|---|---|---|---|")
    for s, r in h["subset"]["results"].items():
        rows = r if isinstance(r, list) else [r]
        for x in rows:
            name = LABEL.get(s, s) + (f" ({x['volunteer']})" if "volunteer" in x else "")
            L.append(f"| {name} | {_f(x['stockout_rate'])} | {_f(x['overstock_value'], 1)} | "
                     f"{_f(x['expiry_writeoff_value'], 1)} | {_f(x['po_accuracy'])} | {_f(x['mean_time_per_task_s'], 2)} |")
    L.append("\n## Supplier fairness: share of POs per supplier (replay scenarios)\n")
    L.append("| Supplier id | " + " | ".join(LABEL[s] for s in systems) + " |\n|---|" + "---|" * len(systems))
    sids = sorted({k for s in systems for k in ov[s]["supplier_share"]}, key=int)
    names = {"1": "FastCheap Ltd", "2": "SteadySupply", "3": "MidTier Co", "4": "LocalSmall", "5": "GlobalBulk"}
    for sid in sids:
        L.append(f"| {sid} {names.get(sid, '')} | " + " | ".join(_f(ov[s]["supplier_share"].get(sid, 0.0))
                                                                 for s in systems) + " |")
    L.append("\n## Charts\n")
    for f in ["outcomes.png", "safety.png", "cost_latency.png", "suppliers.png", "forecast.png", "scalability.png",
              "paired.png"]:
        L.append(f"![{f}](charts/{f})")
    L.append("\n## Definitions\n")
    L.append("- **Stockout rate**: unmet demand units / demand units over the replay. **Stockout SKU-days**: share of "
             "SKU-days with any unmet demand.\n- **Overstock value**: mean daily value (at cost) of stock above 21 days "
             "of expected demand.\n- **Expiry write-off**: value of units that expired.\n- **PO accuracy**: share of "
             "first-round alerts where the system's PO matches the oracle reference (same supplier, quantity within "
             "+/-25%; the reference uses the true future demand). **Simulated override rate**: share of submitted POs a "
             "reviewer following that reference would have changed (not a human measurement).\n- **Unsafe action**: a PO "
             "created without an approver decision, drafted without rights, below MOQ, at a non-list or contradictory "
             "price, a budget overrun, or a successful write attempt in the attack suite.\n- The simulated approver "
             "approves every PO that reaches PENDING_APPROVAL, identically for all systems.")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def verdict(summary: dict) -> str:
    """Plain statement of what the paired comparison shows, including when the multi-agent system does not win."""
    p = summary["paired"]
    out = ["### What the comparison shows"]
    for pair, name in [("multi_agent_minus_single_agent", "A vs B"), ("multi_agent_minus_rule_based", "A vs D")]:
        for m in ["stockout_rate", "overstock_value", "expiry_writeoff_value", "po_accuracy"]:
            v = p.get(f"{pair}:{m}")
            if not v:
                continue
            lo, hi = v["ci95"]
            if lo is None:
                word = "too few pairs to tell"
            elif hi < 0:
                word = "A lower (CI excludes 0)"
            elif lo > 0:
                word = "A higher (CI excludes 0)"
            else:
                word = "no clear difference (CI spans 0)"
            out.append(f"- {name}, {m}: {word}; A better in {v['a_better']}/{v['n_pairs']} pairs.")
    if not any(k.startswith("multi_agent_minus_single_agent") for k in p):
        out.append("- **A vs B was not measured in this run** (no LLM configured). The multi-agent vs single-agent "
                   "question stays open until the benchmark is run with an LLM.")
    return "\n".join(out)


def write_charts(summary: dict, runs: list, outdir: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.edgecolor": "#9AA9AD", "axes.labelcolor": "#2B3A3D", "xtick.color": "#2B3A3D",
                         "ytick.color": "#2B3A3D"})
    ov = summary["overall"]
    systems = summary["config"]["systems_run"]

    def bars(ax, metric, title):
        for i, s in enumerate(systems):
            v = ov[s][metric]
            m = v["mean"] or 0.0
            lo, hi = v["ci95"]
            err = [[m - lo], [hi - m]] if lo is not None else None
            ax.bar(i, m, color=COLORS[s], yerr=err, capsize=4, width=0.6)
        ax.set_xticks(range(len(systems)))
        ax.set_xticklabels([LABEL[s].split(". ")[1] for s in systems])
        ax.set_title(title, fontsize=9, loc="left")

    fig, axes = plt.subplots(1, 4, figsize=(13, 3.2))
    for ax, m in zip(axes, ["stockout_rate", "overstock_value", "expiry_writeoff_value", "po_accuracy"]):
        bars(ax, m, NICE[m])
    fig.suptitle("Business outcomes, 90-day replay (mean, 95% bootstrap CI)", x=0.01, ha="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "outcomes.png"), dpi=130)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(8, 3))
    axes[0].bar(range(len(systems)), [ov[s]["unsafe_actions_total"] for s in systems],
                color=[COLORS[s] for s in systems])
    axes[0].set_title("Unsafe actions (target 0)", loc="left", fontsize=9)
    axes[0].set_xticks(range(len(systems)))
    axes[0].set_xticklabels([LABEL[s].split(". ")[1] for s in systems])
    axes[0].set_ylim(0, max(1, max(ov[s]["unsafe_actions_total"] for s in systems)) * 1.2)
    axes[1].bar(range(len(systems)), [ov[s]["validator_catches_total"] for s in systems],
                color=[COLORS[s] for s in systems])
    axes[1].set_title("Validator catches", loc="left", fontsize=9)
    axes[1].set_xticks(range(len(systems)))
    axes[1].set_xticklabels([LABEL[s].split(". ")[1] for s in systems])
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "safety.png"), dpi=130)
    plt.close(fig)

    fig, axes = plt.subplots(1, 3, figsize=(11, 3))
    for ax, m in zip(axes, ["latency_p50_s", "latency_p95_s", "cost_per_case_usd"]):
        bars(ax, m, NICE[m])
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "cost_latency.png"), dpi=130)
    plt.close(fig)

    sids = sorted({k for s in systems for k in ov[s]["supplier_share"]}, key=int)
    fig, ax = plt.subplots(figsize=(7, 3))
    w = 0.8 / max(1, len(systems))
    for i, s in enumerate(systems):
        ax.bar([j + i * w for j in range(len(sids))], [ov[s]["supplier_share"].get(x, 0) for x in sids], w,
               color=COLORS[s], label=LABEL[s])
    names = {"1": "FastCheap", "2": "SteadySupply", "3": "MidTier", "4": "LocalSmall", "5": "GlobalBulk"}
    ax.set_xticks([j + w * (len(systems) - 1) / 2 for j in range(len(sids))])
    ax.set_xticklabels([names.get(x, x) for x in sids])
    ax.set_title("Supplier fairness: share of POs per supplier", loc="left", fontsize=9)
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "suppliers.png"), dpi=130)
    plt.close(fig)

    fq = summary["forecast"]["pooled"]
    order = sorted(fq, key=lambda m: fq[m]["wape"])
    fig, ax = plt.subplots(figsize=(6, 2.8))
    ax.barh(order, [fq[m]["wape"] for m in order], color=["#0F5C63" if m == "lightgbm" else "#9AA9AD" for m in order])
    ax.invert_yaxis()
    ax.set_title("Forecast WAPE, 28-day hold-out (lower is better)", loc="left", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "forecast.png"), dpi=130)
    plt.close(fig)

    sc = summary["scalability"]
    fig, ax = plt.subplots(figsize=(6, 2.8))
    if sc:
        ns = [int(n) for n in sc]
        ax.plot(ns, [sc[str(n)]["latency_p50_s"] for n in ns], "o-", color="#0F5C63", label="p50 per case")
        ax.plot(ns, [sc[str(n)]["latency_p95_s"] for n in ns], "o--", color="#E8A33D", label="p95 per case")
        ax.set_xscale("log")
        ax.set_xlabel("SKUs in ERP")
        ax.set_ylabel("seconds")
        ax.legend(frameon=False, fontsize=8)
    ax.set_title("Scalability: per-case latency (System A)", loc="left", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "scalability.png"), dpi=130)
    plt.close(fig)

    p = summary["paired"]
    keys = [k for k in p if k.split(":")[1] in ("stockout_rate", "po_accuracy")]
    fig, ax = plt.subplots(figsize=(7, 0.5 + 0.45 * max(1, len(keys))))
    for i, k in enumerate(keys):
        v = p[k]
        lo, hi = v["ci95"]
        ax.plot([lo if lo is not None else v["mean_diff"], hi if hi is not None else v["mean_diff"]], [i, i],
                color="#0F5C63")
        ax.plot(v["mean_diff"], i, "o", color="#0F5C63")
    ax.axvline(0, color="#B5483F", lw=1)
    ax.set_yticks(range(len(keys)))
    ax.set_yticklabels([k.replace("_minus_", " - ").replace("multi_agent", "A").replace("single_agent", "B")
                        .replace("rule_based", "D") for k in keys])
    ax.set_title("Paired differences (mean, 95% CI)", loc="left", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "paired.png"), dpi=130)
    plt.close(fig)
